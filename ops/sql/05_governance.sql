GRANT SELECT ON ALL TABLES IN SCHEMA DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_LUZON;
GRANT SELECT ON ALL TABLES IN SCHEMA DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_VISMIN;
GRANT SELECT ON ALL VIEWS IN SCHEMA DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_NCR;
GRANT SELECT ON ALL VIEWS IN SCHEMA DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_LUZON;
GRANT SELECT ON ALL VIEWS IN SCHEMA DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_VISMIN;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_NCR;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_LUZON;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_VISMIN;

USE ROLE SECURITYADMIN;   -- future grants in a non-managed schema need the schema owner or MANAGE GRANTS
GRANT SELECT ON FUTURE TABLES IN SCHEMA TELCO_PROD_XL_V2.DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_NCR;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TELCO_PROD_XL_V2.DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_LUZON;
GRANT SELECT ON FUTURE TABLES IN SCHEMA TELCO_PROD_XL_V2.DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_VISMIN;
