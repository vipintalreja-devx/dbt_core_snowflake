GRANT SELECT ON FUTURE VIEWS IN SCHEMA TELCO_PROD_XL_V2.DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_LUZON;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA TELCO_PROD_XL_V2.DBT_TELCO_GOLD TO ROLE TELCO_ANALYST_VISMIN;

USE ROLE SYSADMIN;
-- the map is maintained by dbt from a version-controlled seed
GRANT SELECT, INSERT, DELETE ON TABLE GOV.REGION_ACCESS_MAP TO ROLE DBT_ROLE;
-- dbt re-attaches the policy to gold tables after every build
GRANT APPLY ON ROW ACCESS POLICY GOV.RAP_REGION TO ROLE DBT_ROLE;

-- Policy: same intent ("an analyst role sees only the regions mapped to it"), now
--   * the ETL role is exempt explicitly (no reliance on secondary roles)
--   * regions without a name (id 2) are addressable as 'REGION_<id>'
ALTER ROW ACCESS POLICY GOV.RAP_REGION SET BODY ->
  IS_ROLE_IN_SESSION('ACCOUNTADMIN') OR IS_ROLE_IN_SESSION('SYSADMIN') OR IS_ROLE_IN_SESSION('MIG_AGENT')
  OR IS_ROLE_IN_SESSION('TRANSPILER_RO') OR IS_ROLE_IN_SESSION('DBT_ROLE')
  OR EXISTS (SELECT 1 FROM GOV.REGION_ACCESS_MAP m
               JOIN REF.GEO_REGION g
                 ON COALESCE(NULLIF(TRIM(g.REGION_NAME), ''), 'REGION_' || g.REGION_ID) = m.REGION_NAME
              WHERE g.REGION_ID = RID AND IS_ROLE_IN_SESSION(m.ROLE_NAME));

-- Companion policy for gold tables that carry only REGION_NAME (e.g. ARPU / churn marts).
-- Same map, same exemptions; gold shows region 2 as 'UNKNOWN', mapped via 'REGION_2'.
USE ROLE SYSADMIN;
CREATE ROW ACCESS POLICY IF NOT EXISTS GOV.RAP_REGION_NAME AS (RNAME VARCHAR) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('ACCOUNTADMIN') OR IS_ROLE_IN_SESSION('SYSADMIN') OR IS_ROLE_IN_SESSION('MIG_AGENT')
  OR IS_ROLE_IN_SESSION('TRANSPILER_RO') OR IS_ROLE_IN_SESSION('DBT_ROLE')
  OR EXISTS (SELECT 1 FROM GOV.REGION_ACCESS_MAP m
              WHERE IS_ROLE_IN_SESSION(m.ROLE_NAME)
                AND (UPPER(m.REGION_NAME) = UPPER(RNAME) OR (RNAME = 'UNKNOWN' AND m.REGION_NAME = 'REGION_2')))
  COMMENT = 'Analyst roles see only the regions mapped to them (tables keyed by region name)';
GRANT APPLY ON ROW ACCESS POLICY GOV.RAP_REGION_NAME TO ROLE DBT_ROLE;
