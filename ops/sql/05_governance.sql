GRANT USAGE ON DATABASE TELCO_PROD_XL_V2 TO ROLE TELCO_ANALYST_LUZON;
GRANT USAGE ON DATABASE TELCO_PROD_XL_V2 TO ROLE TELCO_ANALYST_VISMIN;
GRANT USAGE ON SCHEMA NETWORK TO ROLE TELCO_ANALYST_NCR;
GRANT USAGE ON SCHEMA NETWORK TO ROLE TELCO_ANALYST_LUZON;
GRANT USAGE ON SCHEMA NETWORK TO ROLE TELCO_ANALYST_VISMIN;
GRANT SELECT ON TABLE NETWORK.OUTAGE_INCIDENT TO ROLE TELCO_ANALYST_NCR;
GRANT SELECT ON TABLE NETWORK.OUTAGE_INCIDENT TO ROLE TELCO_ANALYST_LUZON;
GRANT SELECT ON TABLE NETWORK.OUTAGE_INCIDENT TO ROLE TELCO_ANALYST_VISMIN;

-- gold is owned by DBT_ROLE: it grants read access to the analysts (current + future objects)
