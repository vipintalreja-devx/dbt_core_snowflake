GRANT ROLE TELCO_ANALYST_NCR    TO ROLE SYSADMIN;
GRANT ROLE TELCO_ANALYST_LUZON  TO ROLE SYSADMIN;
GRANT ROLE TELCO_ANALYST_VISMIN TO ROLE SYSADMIN;

