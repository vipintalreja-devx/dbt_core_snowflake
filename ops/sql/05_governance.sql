-- 05_governance.sql -- Batch: regional row-level security that actually filters.
--   * 3 regional analyst roles (BI service users get these as default roles, 08_bi.sql)
--   * RAP_REGION body: DBT_ROLE exempt explicitly; unnamed region 2 mappable as 'REGION_2'
--   * DBT_ROLE may maintain GOV.REGION_ACCESS_MAP (from seeds/region_access_map.csv)
--     and attach RAP_REGION to gold tables (post-hook macros/apply_row_access_policy.sql)
-- GOV.REGION_ACCESS_MAP keeps its shape (ROLE_NAME, REGION_NAME).
-- =============================================================================
USE ROLE USERADMIN;
