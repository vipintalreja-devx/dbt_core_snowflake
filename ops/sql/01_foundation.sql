-- ---------------------------------------------------------------- ACCOUNTADMIN
USE ROLE ACCOUNTADMIN;

-- Warehouses: builds vs BI separated (resource monitor attached after backfill, see 09_cost.sql)
CREATE WAREHOUSE IF NOT EXISTS ETL_WH WAREHOUSE_SIZE = 'SMALL'  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE COMMENT = 'Ingestion, native pipelines and dbt builds';
CREATE WAREHOUSE IF NOT EXISTS BI_WH  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE COMMENT = 'Tableau / Power BI service users';
GRANT OWNERSHIP ON WAREHOUSE ETL_WH TO ROLE SYSADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON WAREHOUSE BI_WH  TO ROLE SYSADMIN COPY CURRENT GRANTS;

-- Role hierarchy best practice: custom roles roll up to SYSADMIN
GRANT ROLE DBT_ROLE TO ROLE SYSADMIN;

-- Account-level privileges the scheduler needs
GRANT EXECUTE TASK ON ACCOUNT TO ROLE DBT_ROLE;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE SYSADMIN;
-- ACCESS_HISTORY / TASK_HISTORY / COPY_HISTORY for lineage + QA views
