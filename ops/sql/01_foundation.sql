-- Policy exemptions for the ETL role. Today DBT_ROLE only gets through because the
-- interactive user carries ACCOUNTADMIN as a secondary role; a scheduled task does not.
-- Body = existing body + IS_ROLE_IN_SESSION('DBT_ROLE'); nothing else changes.
ALTER ROW ACCESS POLICY GOV.RAP_PARTNER_BRAND SET BODY ->
  IS_ROLE_IN_SESSION('TRANSPILER_RO')
  OR IS_ROLE_IN_SESSION('TRANSPILER_BASELINE_OWNER')
  OR IS_ROLE_IN_SESSION('TELCO_PII_ANALYST')
  OR IS_ROLE_IN_SESSION('SYSADMIN')
  OR IS_ROLE_IN_SESSION('DBT_ROLE')
  OR EXISTS (SELECT 1 FROM PARTNER.PARTNER_BRAND b
              WHERE b.PARTNER_BRAND_ID = BRAND_ID AND IS_ROLE_IN_SESSION(b.OWNER_ROLE));

ALTER AGGREGATION POLICY GOV.AP_NPS_MIN_GROUP SET BODY ->
  CASE WHEN IS_ROLE_IN_SESSION('ACCOUNTADMIN') OR IS_ROLE_IN_SESSION('SYSADMIN') OR IS_ROLE_IN_SESSION('MIG_AGENT')
            OR IS_ROLE_IN_SESSION('TRANSPILER_RO') OR IS_ROLE_IN_SESSION('DBT_ROLE')
       THEN NO_AGGREGATION_CONSTRAINT()
       ELSE AGGREGATION_CONSTRAINT(MIN_GROUP_SIZE => 50) END;

ALTER MASKING POLICY GOV.MP_DOB_CONSENT SET BODY ->
  CASE WHEN IS_ROLE_IN_SESSION('ACCOUNTADMIN') OR IS_ROLE_IN_SESSION('SYSADMIN') OR IS_ROLE_IN_SESSION('MIG_AGENT')
            OR IS_ROLE_IN_SESSION('TELCO_PII_ANALYST') OR IS_ROLE_IN_SESSION('DBT_ROLE') THEN VAL
       WHEN ARRAY_SIZE(FLAGS) >= 3 THEN VAL
       ELSE DATE_TRUNC('year', VAL) END;
